create or replace function public.rebuild_draft_fsy_ids(p_session_id uuid)
returns integer
language plpgsql
security definer
set search_path=''
as $$
declare inserted_count integer;
begin
  if not private.has_capability(p_session_id,'registration_manage') then raise exception 'Registration management access required'; end if;
  if exists(select 1 from public.participant_badge_assignments where session_id=p_session_id and state='finalized') then
    raise exception 'FSY IDs are already finalized. Use the vacancy/replacement workflow for day-of changes';
  end if;

  delete from public.participant_badge_assignments where session_id=p_session_id and state='draft';

  with eligible as (
    select p.id participant_id,p.session_id,p.group_id,p.sex,p.first_name,p.last_name,
      trim(concat_ws(' ',p.first_name,p.last_name)) full_name,
      g.company_id,
      coalesce(g.operational_number,nullif(regexp_replace(g.name,'\D','','g'),'')::integer) group_number,
      coalesce(c.operational_number,nullif(regexp_replace(c.name,'\D','','g'),'')::integer) company_number,
      private.origin_code_for_participant(p) origin_code
    from public.participants p
    join public.counselor_groups g on g.id=p.group_id
    join public.companies c on c.id=g.company_id
    where p.session_id=p_session_id and private.operational_participant_is_eligible(p_session_id,p.id)
  ), ranked as (
    select e.*,
      row_number() over(partition by e.company_id order by
        case when e.sex='female' then 0 else 1 end,
        e.group_number nulls last,
        lower(e.last_name),lower(e.first_name),e.participant_id
      )::integer slot_number
    from eligible e
  )
  insert into public.participant_badge_assignments(
    session_id,participant_id,company_id,group_id,slot_number,origin_code,fsy_id,badge_name,state,assigned_by
  )
  select r.session_id,r.participant_id,r.company_id,r.group_id,r.slot_number,r.origin_code,
    r.origin_code||'-C'||lpad(r.company_number::text,2,'0')||'-'||lpad(r.slot_number::text,2,'0'),
    r.full_name,'draft',(select auth.uid())
  from ranked r
  where r.origin_code is not null and r.company_number is not null;

  get diagnostics inserted_count = row_count;
  insert into public.audit_events(session_id,actor_id,action,entity_type,entity_id,metadata)
  values(p_session_id,(select auth.uid()),'fsy_ids_rebuilt','session',p_session_id::text,jsonb_build_object('draft_ids',inserted_count,'ordering','female_groups_first_then_male_groups; alphabetical within group'));
  return inserted_count;
end;
$$;

create or replace function public.finalize_fsy_ids(p_session_id uuid)
returns integer
language plpgsql
security definer
set search_path=''
as $$
declare missing_count integer; finalized_count integer;
begin
  if not private.has_capability(p_session_id,'registration_manage') then raise exception 'Registration management access required'; end if;

  select count(*)::int into missing_count
  from public.participants p
  where p.session_id=p_session_id and p.group_id is not null and private.operational_participant_is_eligible(p_session_id,p.id)
    and not exists(select 1 from public.participant_badge_assignments b where b.participant_id=p.id and b.session_id=p_session_id and b.state<>'retired');
  if missing_count>0 then raise exception '% eligible grouped participants still need an FSY ID. Resolve missing origin codes first',missing_count; end if;

  update public.participant_badge_assignments
  set state='finalized',finalized_by=(select auth.uid()),finalized_at=coalesce(finalized_at,now())
  where session_id=p_session_id and state='draft';
  get diagnostics finalized_count = row_count;

  insert into public.audit_events(session_id,actor_id,action,entity_type,entity_id,metadata)
  values(p_session_id,(select auth.uid()),'fsy_ids_finalized','session',p_session_id::text,jsonb_build_object('finalized_now',finalized_count));
  return finalized_count;
end;
$$;

