create or replace function private.origin_code_for_participant(p_participant public.participants)
returns text
language sql
stable
security definer
set search_path=''
as $$
  select o.code
  from public.origin_code_registry o
  where o.session_id=p_participant.session_id
    and o.active
    and (
      lower(trim(o.canonical_name))=lower(trim(coalesce(p_participant.stake_name,'')))
      or exists(select 1 from unnest(o.aliases) alias where lower(trim(alias))=lower(trim(coalesce(p_participant.stake_name,''))))
    )
  order by case when lower(trim(o.canonical_name))=lower(trim(coalesce(p_participant.stake_name,''))) then 0 else 1 end
  limit 1;
$$;

create or replace function public.get_origin_code_registry(p_session_id uuid)
returns table(canonical_name text, code text, aliases text[], participant_count integer)
language plpgsql
stable
security definer
set search_path=''
as $$
begin
  if not private.has_session_access(p_session_id) then raise exception 'Session access required'; end if;
  return query
  select o.canonical_name,o.code,o.aliases,
    count(p.id)::integer
  from public.origin_code_registry o
  left join public.participants p on p.session_id=o.session_id and (
    lower(trim(coalesce(p.stake_name,'')))=lower(trim(o.canonical_name))
